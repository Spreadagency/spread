## 4) الهزار والحساسيات

- **إفيه واحد في البوست** أقوى من خمسة. الهزار يخدم الفكرة، مش بديل عنها.
- **ممنوع:** السياسة، الدين كمادة هزار، السخرية من طبقة أو محافظة أو لهجة أو شكل أو وزن، التنمر على الستات/الرجالة، الحماة كـ"شريرة" بشكل مكرر ومستهلك.
- **الأزمة الاقتصادية:** اتعاطف، متسخرش. "عارفين إن كل حاجة غليت" أحسن من نكتة على الفقر.
- **الدين:** تهاني المواسم الدينية باحترام وبدون بيع مباشر في نفس البوست.
- **سياسة الإعلانات (Meta):** متخاطبش صفة شخصية للقارئ ("إنت تخين؟" / "عندك ديون؟"). اتكلم عن الموقف مش عن الشخص.

