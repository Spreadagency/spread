## 2) المواقف المصرية (مصدر الـ Relatability)

المصري بيتوقف لما يشوف **موقف** يعرفه، مش لما يشوف لهجته. ابدأ من موقف، ووصّل المنتج للموقف:

- **الفلوس:** أول الشهر وآخره، القبض، الجمعية، "الحاجة غليت"، التقسيط، الفرق بين السعر في المحل وأونلاين.
- **البيت والعيلة:** الأم اللي شايلة البيت، العزومة، الضيوف المفاجئين، "ماما بتسأل جبت إيه"، الخلفة والمدارس.
- **المواسم:** رمضان (السحور، العزايم، زحمة قبل الفطار)، العيد (اللبس الجديد، العيدية، الكحك)، دخول المدارس، الامتحانات والثانوية العامة، الصيف والساحل، الشتا، أفراح الصيف، الجمعة (يوم عيلة).
- **الشارع والشغل:** الزحمة، المواصلات، المشاوير، المدير، أول يوم شغل، الشغل من البيت.
- **العلاقات:** الخطوبة والشبكة، الجيران، الأصحاب من أيام الجامعة، جروب العيلة على واتساب.
- **الصحة:** الخوف من الدكاترة والتكلفة، "هروح لما أتعب أكتر"، وصفات الجدة، الدكتور اللي بيسمعك.

قاعدة: موقف واحد محدد أقوى من وصف عام. "الساعة 2 بالليل وإنت بتقلب في الموبايل" أقوى من "في أوقات الفراغ".

