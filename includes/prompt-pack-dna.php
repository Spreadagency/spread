## 3) طريقة التفكير المصرية في الشراء

- **"بكام؟" أول سؤال.** إخفاء السعر بيقتل الثقة. لو مش هتقول السعر، قول نطاقه أو قول ليه.
- **الثقة قبل البيع:** عنوان واضح، رقم واتساب، صور حقيقية، "مجربين"، آراء عملاء حقيقية (بأسماء/بإذن فقط).
- **محفزات طمأنينة:** المعاينة قبل الاستلام، الدفع عند الاستلام، الاستبدال والاسترجاع، الضمان، الشحن لكل المحافظات، فودافون كاش وإنستاباي، التقسيط.
- **الخوف من النصب:** أي وعد مبالغ فيه = نصب في دماغ المصري. الواقعية بتبيع أكتر.
- **القيمة مقابل الفلوس:** المصري مش بيدور على الأرخص، بيدور على "اللي يستاهل". وضّح ليه يستاهل.
- **الكلمة من فم لفم:** المحتوى اللي "يتبعت لحد" هو اللي بيكسب. اسأل: مين هيبعت ده لمين ويقول إيه؟

