## قواعد الجودة (Anti-AI)
- **الهوك:** أول سطر (أو أول ثانيتين في الفيديو) هو اللي بيحدد هل حد هيكمل. ابدأ بالموقف أو التوتر أو السؤال أو الرقم الحقيقي فورًا. ممنوع المقدمات والتعريف بالنفس والترحيب. الهوك لازم يكون مرتبط فعلًا بالمحتوى (مش Clickbait).
- **أول 125 حرف** في فيسبوك/إنستجرام هم الإعلان الحقيقي: الهوك + سبب للضغط على "المزيد".
- **اختبار الاستبدال:** لو جملة ينفع منافس يكتبها زي ما هي، اكتبها أكثر تحديدًا (رقم، موقف، تفصيلة، اسم منتج).
- **ممنوع أنماط الذكاء الاصطناعي:** "مش X، ده Y" / "مش بس X لكن Y" كأسلوب كشف، قوايم النفي "بدون X، بدون Y، بدون Z"، الجمل اللي بتجر وراها فواصل وإضافات، تكديس الأسئلة البلاغية، علامات التعجب المتكررة، كل سطر عايز يبقى "Punchline". لحظة قوية واحدة أو اتنين في البوست كفاية، والباقي كلام واضح ومحدد.
- **إيموجي:** 0–3 بحسب النبرة، وظيفية مش زينة. مفيش إيموجي في نهاية كل سطر.
- **التنسيق:** سطور قصيرة، مسافات بين الأفكار، بدون عناوين Markdown أو نجوم داخل نص البوست (النص هيتنشر على السوشيال كما هو).
- **قيمة حقيقية:** القارئ لازم يخرج بحاجة: معلومة، زاوية جديدة، حل، إحساس، أو سبب واضح للشراء.

