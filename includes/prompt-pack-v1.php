## أنواع المحتوى وطريقة بنائها
- **ستوري تيلنج / قصة:** موقف ← توتر أو مشكلة ← لحظة تحول ← النتيجة ← ربط طبيعي بالبراند. القصة لازم تكون معقولة ومتتنسبش لعميل حقيقي إلا لو موجود في البيانات.
- **إعلاني / بيعي:** مشكلة محددة ← المنتج كحل ← دليل أو تفصيلة مقنعة ← عرض/سعر ← طمأنينة ← CTA.
- **تعليمي / نصائح:** وعد واضح ← 3–5 نقاط مفيدة فعلًا (مش معروفة للكل) ← خلاصة ← CTA خفيف.
- **تفاعلي:** سؤال حقيقي له إجابات مختلفة أو اختيار بين حاجتين، مرتبط بالمجال (مش "اكتب تم").
- **توعوي:** معلومة/خرافة شائعة عند المصريين ← التصحيح ← ليه ده مهم ليك.
- **عرض / خصم:** العرض في أول سطر، الشروط والمدة بوضوح، السبب (موسم/مناسبة)، CTA.
- **مناسبة:** تهنئة صادقة مرتبطة بشعور المناسبة، والبراند في الخلفية مش في الواجهة.
- **ترند / كوميدي:** ترند مناسب للبراند فقط، إفيه واحد قوي، بدون إساءة.
- **قبل وبعد / نتيجة:** فقط لو النتيجة حقيقية وفي البيانات، مع توضيح إن النتايج بتختلف.
- **سؤال وجواب (FAQ):** سؤال حقيقي من اللي بيسألوه العملاء ← إجابة مباشرة ← تفصيلة ثقة.
- **كاروسيل:** كل شريحة فكرة واحدة؛ الشريحة الأولى هوك، الأخيرة CTA. اكتب نص كل شريحة مرقّم داخل المحتوى.
- **سكريبت فيديو:** مقسّم بالمشاهد مع الكلام المنطوق والنص على الشاشة.
لو النوع مش في القائمة، طبّق أقرب منطق ليه.

## معيار التقييم الداخلي (Spread Content Score — من 100)
1. Hook — 20: قوة أول سطر، وضوح الوعد، الفضول، القدرة على إيقاف الـ Scroll، الارتباط بالمحتوى.
2. Relevance — 15: هل بيتكلم عن مشكلة/رغبة/خوف/سؤال حقيقي عند الجمهور المصري المستهدف؟
3. Retention — 15: هل فيه سبب يكمل للآخر؟ تسلسل، توتر، تغيّر، Payoff.
4. Value — 10: هل القارئ خرج بفايدة حقيقية؟
5. Emotional Connection — 10: هل فيه شعور واضح (فضول، طمأنينة، ضحك، أمل، ندم، تعاطف، مفاجأة)؟
6. Shareability — 10: مين هيبعته لمين، وليه؟
7. Trust & Authority — 10: هل بيبني ثقة في البراند (تفاصيل حقيقية، خبرة، شفافية) مش بس Reach؟
8. Visual & Production Potential — 5: هل يتحول لتصميم أو فيديو جذاب بسهولة؟
9. CTA & Business Fit — 5: هل الخطوة الجاية منطقية ومناسبة لمرحلة الجمهور وهدف البراند؟
المعيار مستقل ومش بيجامل: المعلومة الصحيحة ≠ محتوى جيد، والتصميم الحلو ≠ فكرة ناجحة، والهوك الصادم ≠ هوك قوي.

