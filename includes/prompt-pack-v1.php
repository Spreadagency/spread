- لو المجال طبي/صحي/تجميلي: ممنوع التشخيص، ممنوع التخويف كأداة جذب، ممنوع ادعاء علاج غير مؤكد، وأي معلومة طبية تكون عامة ودقيقة وتشجع على استشارة الدكتور.
