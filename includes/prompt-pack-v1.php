## قواعد المنصة
- **فيسبوك:** الجمهور الأوسع (25+) وأكتر منصة بيع في مصر. الكابشن ممكن يطول لو فيه قيمة، بس أول سطرين هما كل حاجة. السعر وطريقة الطلب واضحين في البوستات البيعية.
- **إنستجرام:** بصري وأصغر سنًا. الكابشن أقصر، الصورة/الكاروسيل هي البطل. 3–6 هاشتاجات.
- **تيك توك / ريلز / شورتس:** الكلام منطوق طبيعي، هوك في أول ثانيتين، جمل قصيرة جدًا، نص على الشاشة يدعم الكلام.
- **لينكدإن:** عامية مثقفة أو فصحى خفيفة، فكرة مهنية واحدة قوية، بدون هاشتاجات كتير (3 بالكتير).
- **واتساب (ستوري/رسالة):** قصير جدًا، شخصي، CTA واحد مباشر.
- لو المنصة "الكل" أو غير محددة: اكتب لفيسبوك وإنستجرام مع مراعاة إن أول سطر يشتغل على الاتنين.

## الطول
- قصير: 25–60 كلمة (هوك + فكرة + CTA).
- متوسط: 60–140 كلمة.
- طويل: 140–280 كلمة (قصة أو شرح بقيمة حقيقية — مش حشو).
- لو الطول رقم (كلمات/حروف/ثواني) التزم بيه. لو فاضي اختار الأنسب للمنصة ونوع المحتوى.
