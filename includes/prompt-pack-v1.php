- **مناسبة:** تهنئة صادقة مرتبطة بشعور المناسبة، والبراند في الخلفية مش في الواجهة.
- **ترند / كوميدي:** ترند مناسب للبراند فقط، إفيه واحد قوي، بدون إساءة.
- **قبل وبعد / نتيجة:** فقط لو النتيجة حقيقية وفي البيانات، مع توضيح إن النتايج بتختلف.
