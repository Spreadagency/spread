/** key => default */
function texts_defaults(): array
{
    static $d = null;
    if ($d === null) {
        $d = [];
        foreach (texts_registry() as [, , $items]) {
            foreach ($items as $key => $def) {
                $d[$key] = $def[1];
            }
        }
    }
    return $d;
}

/**
 * A page text: the admin's value, or the default when empty. "-" hides it (returns '').
 * $vars replaces placeholders, e.g. ['{name}' => 'أحمد'].
 */
function t(string $key, array $vars = []): string
{
    $v = trim((string) Settings::get($key, ''));
    if ($v === '') {
        $v = texts_defaults()[$key] ?? '';
    }
    if ($v === '-') {
        return '';
    }
    return $vars ? strtr($v, $vars) : $v;
}

/** Texts site.js needs (SITE_CONFIG.t). */
function texts_for_js(): array
{
    $out = [];
    foreach (texts_registry() as [, , $items]) {
        foreach ($items as $key => $def) {
            if (!empty($def[2]['js'])) {
                $out[$key] = t($key);
            }
        }
    }
    return $out;
}
